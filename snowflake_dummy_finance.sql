CREATE OR REPLACE TABLE QUARTERLY_FINANCE_SUMMARY AS
WITH quarterly AS (
    SELECT FISCAL_QUARTER, SUM(REVENUE_PLAN) AS REVENUE_PLAN,
           SUM(REVENUE_ACTUAL) AS REVENUE_ACTUAL,
           SUM(CUSTOMER_COUNT_PLAN) AS CUSTOMER_COUNT_PLAN,
           SUM(CUSTOMER_COUNT_ACTUAL) AS CUSTOMER_COUNT_ACTUAL
    FROM REVENUE_PLAN GROUP BY FISCAL_QUARTER
), metrics AS (
    SELECT *, LAG(REVENUE_ACTUAL) OVER (ORDER BY FISCAL_QUARTER) AS PRIOR_QUARTER_REVENUE
    FROM quarterly
)
SELECT FISCAL_QUARTER, REVENUE_PLAN, REVENUE_ACTUAL,
       REVENUE_ACTUAL - REVENUE_PLAN AS BEAT_MISS_AMOUNT,
       ROUND((REVENUE_ACTUAL - REVENUE_PLAN) / NULLIF(REVENUE_PLAN, 0) * 100, 1) AS BEAT_MISS_PERCENT,
       ROUND((REVENUE_ACTUAL - PRIOR_QUARTER_REVENUE) / NULLIF(PRIOR_QUARTER_REVENUE, 0) * 100, 1) AS QOQ_REVENUE_GROWTH_PERCENT,
       CUSTOMER_COUNT_PLAN, CUSTOMER_COUNT_ACTUAL,
       CUSTOMER_COUNT_ACTUAL - CUSTOMER_COUNT_PLAN AS CUSTOMER_COUNT_BEAT_MISS
FROM metrics;

CREATE OR REPLACE TABLE GEOGRAPHY_PERFORMANCE AS
SELECT GEOGRAPHY, SUM(REVENUE_PLAN) AS FULL_YEAR_REVENUE_PLAN,
       SUM(REVENUE_ACTUAL) AS FULL_YEAR_REVENUE_ACTUAL,
       SUM(REVENUE_ACTUAL) - SUM(REVENUE_PLAN) AS FULL_YEAR_BEAT_MISS_AMOUNT,
       ROUND((SUM(REVENUE_ACTUAL) - SUM(REVENUE_PLAN)) / NULLIF(SUM(REVENUE_PLAN), 0) * 100, 1) AS FULL_YEAR_BEAT_MISS_PERCENT,
       SUM(CUSTOMER_COUNT_ACTUAL) AS CUSTOMER_COUNT_THROUGH_Q3,
       ROUND(SUM(REVENUE_ACTUAL) / NULLIF(SUM(CUSTOMER_COUNT_ACTUAL), 0), 2) AS REVENUE_PER_CUSTOMER_THROUGH_Q3
FROM REVENUE_PLAN
WHERE REVENUE_ACTUAL > 0
GROUP BY GEOGRAPHY;

