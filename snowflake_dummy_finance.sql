-- Example demo query: actual spend vs budget by category for February 2024
SELECT
    b.DEPARTMENT,
    b.CATEGORY,
    b.BUDGET_AMOUNT,
    ABS(COALESCE(SUM(CASE WHEN t.TRANSACTION_TYPE = 'DEBIT' THEN t.AMOUNT ELSE 0 END), 0)) AS ACTUAL_SPEND,
    b.BUDGET_AMOUNT - ABS(COALESCE(SUM(CASE WHEN t.TRANSACTION_TYPE = 'DEBIT' THEN t.AMOUNT ELSE 0 END), 0)) AS REMAINING_BUDGET
FROM MONTHLY_BUDGETS b
LEFT JOIN TRANSACTIONS t
    ON t.CATEGORY = b.CATEGORY
   AND t.TRANSACTION_DATE >= b.BUDGET_MONTH
   AND t.TRANSACTION_DATE < DATEADD(MONTH, 1, b.BUDGET_MONTH)
WHERE b.BUDGET_MONTH = '2024-02-01'
GROUP BY b.DEPARTMENT, b.CATEGORY, b.BUDGET_AMOUNT
ORDER BY b.DEPARTMENT, b.CATEGORY;

