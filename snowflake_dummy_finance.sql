    BEGINNING_CUSTOMERS NUMBER, NEW_CUSTOMERS NUMBER, CHURNED_CUSTOMERS NUMBER,
    ENDING_CUSTOMERS NUMBER, NET_CUSTOMER_GROWTH NUMBER
